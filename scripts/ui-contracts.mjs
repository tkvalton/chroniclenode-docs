// Writes docs/advanced/user-interface/scene-contracts.md from the code of the interface scenes: the templates the toolkit provides and, for every scene class, the template scene(s) that use
// it, the nodes its script looks for (by name: %Name or $Path), the scene exports it needs filled in and the signals it emits.   node scripts/ui-contracts.mjs
import fs from 'node:fs'
import path from 'node:path'

const addon = 'C:/Users/Rhys/Documents/rpg-toolkit/addons/chroniclenode/'
const uiRoot = addon + 'ui_scenes/'
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const output = path.join(here, '..', 'docs', 'advanced', 'user-interface', 'scene-contracts.md')

function walk(dir, list = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(p, list)
    else list.push(p.split(path.sep).join('/'))
  }
  return list
}
const files = walk(uiRoot)
const rel = f => f.replace(addon, '')

// the scenes whose root node has a script: script path -> scenes
const scenesOf = {}
for (const file of files.filter(f => f.endsWith('.tscn'))) {
  const text = fs.readFileSync(file, 'utf8')
  const scripts = {}
  for (const m of text.matchAll(/\[ext_resource type="Script"[^\]]*path="([^"]+)" id="([^"]+)"\]/g)) scripts[m[2]] = m[1]
  const first = text.indexOf('[node ')
  if (first < 0) continue
  const end = text.indexOf('\n[', first + 1)
  const block = text.slice(first, end < 0 ? text.length : end)
  const s = block.match(/^script = ExtResource\("([^"]+)"\)/m)
  if (s && scripts[s[1]]) {
    const scriptPath = scripts[s[1]].replace('res://addons/chroniclenode/', '')
    ;(scenesOf[scriptPath] ||= []).push(rel(file))
  }
}

// free text goes into a Markdown page that Vue reads: no raw tags
const esc = t => t.replace(/</g, '&lt;').replace(/\{\{/g, '&#123;&#123;')

function parse(file) {
  const text = fs.readFileSync(file, 'utf8')
  const lines = text.split('\n')
  const info = { name: '', extends: '', description: '', nodes: [], exports: [], signals: [] }
  const head = text.match(/^class_name (\w+)(?: extends (\S+))?/m)
  if (!head) return null
  info.name = head[1]
  info.extends = head[2] || ''
  // the description: the ## lines right after the class line
  const classLine = lines.findIndex(l => l.startsWith('class_name '))
  const desc = []
  for (let i = classLine + 1; i < lines.length && lines[i].startsWith('##'); i++) desc.push(lines[i].replace(/^##\s?/, ''))
  info.description = esc(desc.join(' ').trim())
  let comment = []
  lines.forEach(line => {
    if (line.startsWith('##')) { comment.push(line.replace(/^##\s?/, '')); return }
    const note = esc(comment.join(' ').trim())
    comment = []
    let m = line.match(/^@onready var (\w+)(?:: ?([\w.\[\]]+))? ?(?:=|:=) ?(?:(%[\w]+)|\$"?([\w\/%]+)"?|get_node\("([^"]+)"\))/)
    if (m) { info.nodes.push({ variable: m[1], type: m[2] || '', how: m[3] || (m[4] ? '$' + m[4] : m[5]), note }); return }
    m = line.match(/^@export var (\w+): ?([\w.\[\]]+)(?: = (.*))?$/)
    if (m) { info.exports.push({ variable: m[1], type: m[2], note }); return }
    m = line.match(/^signal (\w+)(\(([^)]*)\))?/)
    if (m) info.signals.push({ name: m[1], args: m[3] || '', note })
  })
  return info
}

const classes = []
for (const file of files.filter(f => f.endsWith('.gd'))) {
  const info = parse(file)
  if (!info) continue
  info.file = rel(file)
  info.scenes = scenesOf[info.file] || []
  classes.push(info)
}

// the class pages of the Advanced section: class name -> route
const docsRoot = path.resolve(here, '..', 'docs', 'advanced')
const routes = {}
for (const f of walk(docsRoot).filter(f => f.endsWith('.md'))) {
  const first = fs.readFileSync(f, 'utf8').split('\n').find(l => l.startsWith('# '))
  if (first) routes[first.slice(2).trim()] = '/advanced/' + path.relative(docsRoot, f).split(path.sep).join('/').replace(/\.md$/, '')
}

const areas = [
  ['menus', 'Menus'], ['in_game/HUD', 'HUD'], ['in_game/panels/interaction_panels', 'Interaction panels'], ['in_game/panels', 'UI panels'],
  ['in_game/tooltips', 'Tooltips'], ['in_game/popups', 'Popups'], ['loading_screen', 'Loading screen'], ['splash_screen', 'Splash screen'], ['in_game', 'In game'],
]
const areaOf = c => (areas.find(([prefix]) => c.file.startsWith('ui_scenes/' + prefix)) || ['', 'Other'])[1]
const slug = name => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2').toLowerCase()
const first = text => text.split('. ')[0].replace(/\.$/, '')

let out = `<!-- generated by scripts/ui-contracts.mjs from the code of the interface scenes: change the comments in the code, not this page -->

# Interface scenes: what each script needs

A scene of the interface is a **scene and a script**. The script finds the nodes it needs **by name**, so a scene you build yourself works when it has nodes with the names the script looks for, of the types it expects. This page lists the templates the toolkit provides and, for every scene class, the nodes the script looks for, the exports to fill in and the signals it emits.

How to read it:

- **\`%Name\`** is a node with *Access as Unique Name* on, anywhere in the scene. **\`$Name\`** or **\`$Path/To/Node\`** is a node found by its place under the root, so moving it breaks the script.
- A node the script looks for that is not in your scene is \`null\` in the script, and the part that needs it does nothing. Everything else keeps working.
- Exports are filled in the inspector of the scene root (a scene to instantiate for each row, a texture).
- To build your own scene, see [Building your own interface scene](/advanced/user-interface/building-your-own). The [UI Settings](/basic/game-settings/ui-settings#the-scenes-and-their-roots) editor checks the root class of the scenes you set.

`
const grouped = {}
for (const c of classes) (grouped[areaOf(c)] ||= []).push(c)

// the templates the toolkit provides
const templateRows = []
for (const c of classes) for (const scene of c.scenes) templateRows.push({ area: areaOf(c), scene, name: c.name, what: first(c.description) })
out += `## The templates the toolkit provides\n\n${templateRows.length} scenes in \`res://addons/chroniclenode/\`, each with the class on its root node. Copy one next to your own scenes, change it and set it in [UI Settings](/basic/game-settings/ui-settings), or start from your own scene with the same root class.\n\n| Area | Scene | Root class | What it is |\n|---|---|---|---|\n`
for (const row of templateRows.sort((a, b) => a.area.localeCompare(b.area) || a.scene.localeCompare(b.scene))) {
  out += `| ${row.area} | \`${row.scene.replace('ui_scenes/', '')}\` | [\`${row.name}\`](#class-${slug(row.name)}) | ${row.what.replace(/\|/g, '\\|').slice(0, 160)} |\n`
}
out += '\n'

for (const [, title] of areas.concat([['', 'Other']])) {
  const list = (grouped[title] || []).sort((a, b) => a.name.localeCompare(b.name))
  if (!list.length) continue
  out += `## ${title}\n\n`
  for (const c of list) {
    out += `### ${c.name} {#class-${slug(c.name)}}\n\n`
    out += `\`${c.name}\` extends \`${c.extends || 'RefCounted'}\`${routes[c.name] ? ' ([class page](' + routes[c.name] + '))' : ''}\n\n`
    if (c.description) out += first(c.description) + '.\n\n'
    out += `Script: \`${c.file}\`\n\n`
    if (c.scenes.length) out += `Template scene${c.scenes.length > 1 ? 's' : ''}: ${c.scenes.map(s => '`' + s + '`').join(', ')}\n\n`
    if (c.nodes.length) {
      out += '| Node the script looks for | Type | Found as | What it is |\n|---|---|---|---|\n'
      for (const n of c.nodes) out += `| \`${n.variable}\` | \`${n.type}\` | \`${n.how}\` | ${n.note.replace(/\|/g, '\\|')} |\n`
      out += '\n'
    }
    if (c.exports.length) {
      out += '| Export | Type | What it is |\n|---|---|---|\n'
      for (const e of c.exports) out += `| \`${e.variable}\` | \`${e.type}\` | ${e.note.replace(/\|/g, '\\|')} |\n`
      out += '\n'
    }
    if (c.signals.length) out += 'Signals: ' + c.signals.map(s => '`' + s.name + (s.args ? '(' + s.args + ')' : '') + '`').join(', ') + '\n\n'
    if (!c.nodes.length && !c.exports.length && !c.signals.length) out += 'It looks for no nodes by name.\n\n'
  }
}
fs.mkdirSync(path.dirname(output), { recursive: true })
fs.writeFileSync(output, out)
console.log(`${classes.length} scene classes, ${classes.reduce((n, c) => n + c.nodes.length, 0)} nodes looked for, ${classes.filter(c => c.scenes.length).length} with a template scene`)
